import { format, subtract, greaterThan } from '@/core/money';
import type { SearchProfile } from '@/core/trip/types';
import type { RankedTrip } from './types';

/**
 * "Why this trip?" in human terms (1.10.1 section 9).
 *
 * Section 9 asks for an explanation and forbids "meaningless technical
 * scoring". A user does not want to be told that budget fit scored 0.82 at a
 * weight of 0.24; they want to be told the trip comes in under what they
 * planned to spend and the weather looks good.
 *
 * Every sentence here is built from a figure the deterministic core already
 * produced - the cost engine's total, the scoring engine's factors, the
 * constraint engine's headroom. **Nothing is generated by a model**, and
 * nothing is rounded into a claim the underlying number does not support.
 *
 * This is also the seam where a model could eventually word these better
 * (§24.5): it would replace the phrasing and nothing else, because the facts
 * are settled before it is called and `src/ai/guardrails.ts` would reject any
 * figure it invented.
 */

export interface TripReason {
  /** Short enough to sit in a card, specific enough to be worth reading. */
  readonly text: string;
  /** Which computed factor it came from, for tests and for debugging. */
  readonly source: string;
}

/** Below this share of the target, "well under budget" is a fair claim. */
const COMFORTABLY_UNDER = 0.85;
/** Factor values above this are worth mentioning as a strength. */
const STRONG_FACTOR = 0.75;

const FACTOR_PHRASES: Record<string, string> = {
  weather: 'the forecast looks good for these dates',
  hotel_quality: 'the hotel is well rated',
  location: 'the hotel is close to what you came for',
  flight_quality: 'the flights are straightforward',
  usable_time: 'you get most of the days you are paying for',
  transfer: 'the airport transfer is short',
};

/**
 * Up to three reasons this trip is being shown.
 *
 * Ordered by how much each actually contributed to the ranking, so the first
 * reason is the real one rather than the most flattering.
 */
export function explainTrip(trip: RankedTrip, profile: SearchProfile): TripReason[] {
  const reasons: TripReason[] = [];

  // Budget first: it is what most people are actually deciding on.
  //
  // Computed from the profile passed in rather than read off the trip's
  // eligibility, which was worked out against whichever profile ranked it. The
  // two are normally the same; when they are not, an explanation that mixed
  // them would quote headroom against a budget the reader never set.
  const headroom = subtract(profile.targetBudget, trip.cost.total);
  const underTarget = !greaterThan(trip.cost.total, profile.targetBudget);

  if (underTarget && headroom.amount > 0) {
    const share = trip.cost.total.amount / profile.targetBudget.amount;

    reasons.push({
      source: 'budget',
      text:
        share <= COMFORTABLY_UNDER
          ? `${format(headroom)} under what you planned to spend`
          : `comes in just under your ${format(profile.targetBudget)} target`,
    });
  } else if (greaterThan(trip.cost.total, profile.targetBudget)) {
    // Said plainly rather than omitted. A trip over target that is still shown
    // is being shown for some other reason, and hiding the overspend would
    // make the rest of the explanation dishonest.
    reasons.push({
      source: 'budget',
      text: `${format(subtract(trip.cost.total, profile.targetBudget))} over your target, but within your limit`,
    });
  }

  for (const factor of trip.score.strengths) {
    if (reasons.length >= 3) break;
    if (factor.value < STRONG_FACTOR) continue;

    const phrase = FACTOR_PHRASES[factor.key];
    if (phrase) reasons.push({ source: factor.key, text: phrase });
  }

  // A trip with nothing notable still needs an honest sentence.
  if (reasons.length === 0) {
    reasons.push({
      source: 'fallback',
      text: 'it fits everything you asked for, without standing out on any one thing',
    });
  }

  return reasons.slice(0, 3);
}

/** The reasons as one sentence, for a card that has room for a line not a list. */
export function summariseReasons(reasons: readonly TripReason[]): string {
  const parts = reasons.map((reason) => reason.text);

  if (parts.length <= 1) return capitalise(parts[0] ?? '');

  const last = parts.at(-1)!;
  return capitalise(`${parts.slice(0, -1).join(', ')} and ${last}`);
}

function capitalise(text: string): string {
  return text.length === 0 ? text : `${text[0]!.toUpperCase()}${text.slice(1)}.`;
}
