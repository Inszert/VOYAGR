#!/usr/bin/env node
// Writes devmap-live.js at the repository root: the facts devmap.html shows
// live (branch, last commit, recent commits, uncommitted counts).
//
// It reads git metadata only. It never reads .env and never prints anything
// but its own summary line. Run it with: npm run devmap:update

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(repoRoot, 'devmap-live.js');
// This file is generated by this script, so it must not count as the owner's
// uncommitted work (it would otherwise count itself on the next run).
const SELF = 'devmap-live.js';

function git(args) {
  return execFileSync('git', args, {
    cwd: repoRoot,
    encoding: 'utf8',
    windowsHide: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

// Conventional-commit prefix to the kind devmap.html labels. Anything else is
// "other"; "mixed" is a judgment only a person can make, so it is never inferred.
function kindOf(subject) {
  const m = /^([A-Za-z]+)(\([^)]*\))?!?:/.exec(subject);
  const type = m ? m[1].toLowerCase() : '';
  if (type === 'fix') return 'fix';
  if (type === 'feat') return 'feat';
  if (type === 'docs') return 'docs';
  if (type === 'chore') return 'chore';
  return 'other';
}

function lines(text) {
  return text.split(/\r?\n/).filter((line) => line.length > 0);
}

function main() {
  const branchName = git(['rev-parse', '--abbrev-ref', 'HEAD']).trim();
  const branch = branchName === 'HEAD' ? '(detached HEAD)' : branchName;

  // Format: short hash, ISO date (YYYY-MM-DD), subject. Tab separated.
  const commits = lines(
    git(['log', '-15', '--date=short', '--pretty=format:%h%x09%ad%x09%s']),
  ).map((line) => {
    const [hash, date, ...rest] = line.split('\t');
    const subject = rest.join('\t');
    return { hash, date, subject, kind: kindOf(subject) };
  });
  if (commits.length === 0) {
    throw new Error('no commits found; is this a git repository with history?');
  }
  const head = commits[0];

  const status = lines(git(['status', '--porcelain'])).filter(
    (line) => line.slice(3) !== SELF,
  );
  const untracked = status.filter((line) => line.startsWith('??')).length;

  const live = {
    generated: new Date().toISOString(),
    branch,
    lastCommit: { hash: head.hash, date: head.date, subject: head.subject },
    commits,
    uncommittedPaths: status.length,
    uncommittedUntracked: untracked,
  };

  writeFileSync(outFile, `window.DEVMAP_LIVE = ${JSON.stringify(live)};\n`, 'utf8');
  console.log(
    `devmap-live.js written: ${branch}, ${head.hash}, ${commits.length} commits, ` +
      `${status.length} uncommitted paths (${untracked} untracked)`,
  );
}

try {
  main();
} catch (err) {
  console.error(`devmap:update failed: ${err && err.message ? err.message : err}`);
  process.exitCode = 1;
}
